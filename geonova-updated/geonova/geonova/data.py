def find_city(token: str):
    """Fuzzy city lookup by any alias (KZ/RU/EN)."""
    token = token.strip().lower()
    if not token:
        return None
    best = None
    for city in CITIES:
        for alias in city["aliases"]:
            if alias in token or token in alias:
                if best is None or len(alias) > len(best.get("_matched", "")):
                    best = dict(city, _matched=alias)
    return best


def extract_cities(text: str):
    """Find all cities mentioned in a free-text query."""
    found, lowered = [], " " + text.lower() + " "
    for city in sorted(CITIES, key=lambda c: -max(len(a) for a in c["aliases"])):
        for alias in city["aliases"]:
            if alias in lowered and city["id"] not in [c["id"] for c in found]:
                found.append(city)
                break
    return found
